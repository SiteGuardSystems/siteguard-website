#!/usr/bin/env python3
"""Write data/audit-checklists.json from the SiteGuard Audit checklist build list.

    python scripts/gen-audit-checklists.py <path to BUILD_LIST.csv>

The source is SG_AUDIT_CHECKLIST_BUILD_LIST_Rev02 (siteguard-audit
packages/templates/BUILD_LIST.csv). This repo is public, so the list itself
(document codes, library revisions, notes) is not copied in: only counts by
checklist type, area and build wave. Workflow components (built into the
audit and corrective-action features, not checklists of their own) and
held rows are counted separately and left out of the checklist totals.
"""
import csv
import json
import sys
from collections import Counter
from datetime import date
from pathlib import Path

# Public labels for the app_type column.
TYPES = {
    "SWMS check (generated)": "SWMS checks (one for every SWMS in the library)",
    "ITP verification (generated)": "ITP hold and witness point checks (one for every ITP)",
    "Inspection": "Inspections", "Asset inspection": "Inspections", "Assessment": "Assessments",
    "Verification": "Verifications", "Audit": "Audits", "Desk checklist": "Desk checklists",
    "Condition report": "Condition reports", "Test record": "Test records", "Observation": "Observations",
    "Survey": "Surveys", "Report": "Reports",
}
# Public groups for the area column.
AREAS = {
    "Safety": "Safety", "Quality": "Quality", "Environment": "Environment",
    "Audit": "Management systems", "Systems": "Management systems", "Governance": "Management systems",
    "Info security": "Management systems", "Business continuity": "Management systems", "Energy": "Management systems",
    "Sustainability": "Management systems", "Risk": "Management systems",
    "Property": "Property and buildings", "Building surveying": "Property and buildings", "Building compliance": "Property and buildings",
    "Building inspection": "Property and buildings",
    "Transport": "Other workplaces", "Construction-adjacent": "Other workplaces", "Aged care": "Other workplaces",
    "Childcare": "Other workplaces", "Food": "Other workplaces",
}


def main(src):
    rows = list(csv.DictReader(open(src, encoding="utf-8")))
    components = [r for r in rows if r["mode"] == "component"]
    held = [r for r in rows if r["wave"] == "Held"]
    checklists = [r for r in rows if r["mode"] != "component" and r["wave"] != "Held"]
    unknown = sorted({r["app_type"] for r in checklists if r["app_type"] not in TYPES} | {r["area"] for r in checklists if r["area"] not in AREAS})
    if unknown: raise SystemExit(f"add public labels for: {unknown}")
    by_type = Counter(TYPES[r["app_type"]] for r in checklists)
    by_area = Counter(AREAS[r["area"]] for r in checklists)
    by_wave = Counter(r["wave"] for r in checklists)
    out = {
        "note": "Generated by scripts/gen-audit-checklists.py from SG_AUDIT_CHECKLIST_BUILD_LIST_Rev02 (siteguard-audit packages/templates/BUILD_LIST.csv). Counts only; the list itself stays in the private repo. Do not edit by hand.",
        "source": {"list": "SG_AUDIT_CHECKLIST_BUILD_LIST_Rev02", "rows": len(rows), "generated": date.today().isoformat()},
        "checklists": len(checklists),
        "workflow_components": len(components),
        "held": len(held),
        "by_type": dict(by_type.most_common()),
        "by_area": dict(by_area.most_common()),
        "by_wave": {w: by_wave[w] for w in ("v1", "W1", "W2", "W3", "W4") if by_wave[w]},
    }
    dest = Path(__file__).resolve().parent.parent / "data" / "audit-checklists.json"
    dest.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {dest}: {len(checklists)} checklists, {len(components)} workflow components, {len(held)} held")


if __name__ == "__main__":
    if len(sys.argv) != 2: raise SystemExit(__doc__)
    main(sys.argv[1])
